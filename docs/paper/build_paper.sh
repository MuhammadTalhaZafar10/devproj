#!/usr/bin/env bash
# Build the paper: Markdown -> HTML (citations, MathML) -> PDF (Chromium), and a LaTeX export.
#   bash docs/paper/build_paper.sh
# Needs: pandoc >= 2.11 (built-in citeproc) and chromium. Figures: .venv/bin/python docs/paper/make_figures.py
set -euo pipefail
cd "$(dirname "$0")"

pandoc paper.md --from markdown+smart --standalone --citeproc --mathml --self-contained \
  --css style.css --metadata pagetitle="BDG2 performance-class classification" \
  -o paper.html

CHROME="${CHROME_BIN:-$(command -v chromium || command -v chromium-browser || command -v google-chrome)}"
"$CHROME" --headless --no-sandbox --disable-gpu --no-pdf-header-footer \
  --virtual-time-budget=20000 --print-to-pdf=paper.pdf "file://$PWD/paper.html" 2>/dev/null

# LaTeX source for submission systems (generated by pandoc; not compiled in this environment)
pandoc paper.md --from markdown+smart --standalone --citeproc -V documentclass=article -V geometry:margin=2.2cm \
  -V fontsize=10pt -o paper.tex

echo "built: $(ls -la paper.pdf | awk '{print $5}') bytes paper.pdf, paper.tex, paper.html"
